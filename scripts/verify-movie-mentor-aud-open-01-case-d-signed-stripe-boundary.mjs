import assert from "node:assert/strict";
import Stripe from "stripe";
import {createMovieMentorStripeCommercialProviderAdapter} from "../ai/MovieMentorStripeCommercialProviderAdapter.js";
const secret="whsec_aud_open_01_local_signature_only";
const stripe=new Stripe("sk_test_aud_open_01_local_no_network",{apiVersion:"2025-09-30.clover"});
const adapter=createMovieMentorStripeCommercialProviderAdapter({stripe,webhookSecret:secret,successUrl:"https://example.invalid/success",cancelUrl:"https://example.invalid/cancel"});
const event={id:"evt_aud_open_01_signed_partial_chargeback",object:"event",type:"charge.dispute.funds_withdrawn",livemode:false,data:{object:{id:"dp_aud_open_01",object:"dispute",payment_intent:"pi_aud_open_01",amount:300,currency:"gbp"}}};
const rawBody=JSON.stringify(event);
const signature=stripe.webhooks.generateTestHeaderString({payload:rawBody,secret});
const verified=await adapter.verifyDelivery({delivery:{rawBody:Buffer.from(rawBody),signature}});
assert.equal(verified.verified,true);
const normalized=await adapter.normalizeEvent({verifiedDelivery:verified});
assert.equal(normalized.provider,"stripe");
assert.equal(normalized.eventId,event.id);
assert.equal(normalized.commercialReversal,true);
assert.equal(normalized.reversalKind,"dispute");
assert.equal(normalized.reversalAmountMinor,300);
assert.equal(normalized.providerPaymentReference,"pi_aud_open_01");
assert.equal(normalized.currency,"GBP");
await assert.rejects(()=>adapter.verifyDelivery({delivery:{rawBody:Buffer.from(rawBody.replace("300","301")),signature}}),error=>error?.code==="MOVIE_MENTOR_STRIPE_SIGNATURE_INVALID");
await assert.rejects(()=>adapter.verifyDelivery({delivery:{rawBody:Buffer.from(rawBody),signature:"t=1,v1=invalid"}}),error=>error?.code==="MOVIE_MENTOR_STRIPE_SIGNATURE_INVALID");
